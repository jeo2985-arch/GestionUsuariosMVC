    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
         String nombre = jTextField1.getText().trim();
    String apellido = jTextField2.getText().trim();
    String textoSalario = jTextField3.getText().trim();

    if (nombre.isEmpty() || apellido.isEmpty()
            || textoSalario.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Complete todos los campos");
        return;
    }

    try {

        double salario = Double.parseDouble(textoSalario);

        if (!Double.isFinite(salario) || salario <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Ingrese un salario válido");
            return;
        }

        Empleado emp = new Empleado();

        emp.setNombre(nombre);
        emp.setApellido(apellido);
        emp.setSalarioBase(salario);
        emp.setEstado("ACTIVO");

        EmpleadoDAO dao = new EmpleadoDAO();

        boolean resultado = dao.insertarEmpleado(emp);

        if (resultado) {

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Empleado registrado correctamente");

            cargarEmpleados();

            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Error al registrar empleado");
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "El salario debe ser numérico");
    }
    }//GEN-LAST:event_jButton2ActionPerformed

